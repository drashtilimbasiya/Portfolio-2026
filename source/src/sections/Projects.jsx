import { useState } from 'react'
import SectionHeading from '../components/SectionHeading.jsx'
import Reveal from '../components/Reveal.jsx'
import Gallery from '../components/Gallery.jsx'
import Icon from '../components/Icons.jsx'
import Lightbox from '../components/Lightbox.jsx'
import { projects } from '../data/projects.js'
import { asset } from '../asset.js'

function BillViewer({ bill }) {
  const [open, setOpen] = useState(null)
  return (
    <div className="bill card">
      <button className="bill__img" onClick={() => setOpen(0)} aria-label="View sample bill larger">
        <img src={asset(bill.preview)} alt="Sample PDF bill generated by the Patel Auto Garage app" loading="lazy" />
        <span className="shot__zoom"><Icon name="zoom" size={18} /></span>
      </button>
      <div className="bill__text">
        <span className="eyebrow">PDF generation</span>
        <h4>{bill.title}</h4>
        <p>{bill.text}</p>
        <div className="btn-row">
          <a className="btn btn--primary btn--sm" href={asset(bill.pdf)} target="_blank" rel="noreferrer"><Icon name="eye" size={16} /> Open original PDF</a>
          <a className="btn btn--ghost btn--sm" href={asset(bill.pdf)} download><Icon name="download" size={16} /> Download</a>
        </div>
      </div>
      <Lightbox
        items={[{ src: bill.preview, caption: 'Sample bill generated by the app' }]}
        index={open}
        onChange={setOpen}
        onClose={() => setOpen(null)}
        openHref={bill.pdf}
        openLabel="Open original PDF"
      />
    </div>
  )
}

function Project({ p }) {
  const [tab, setTab] = useState(p.modules[0].id)
  const mod = p.modules.find((m) => m.id === tab)
  const repo = mod.github || p.github
  const hasRepo = Boolean(p.github || p.modules.some((m) => m.github))

  return (
    <article className="project" id={p.id}>
      <Reveal className="project__head">
        <span className="project__index">{p.index}</span>
        <div>
          <span className="eyebrow">{p.type}</span>
          <h3>{p.title}</h3>
          <p className="project__sub">{p.subtitle}</p>
        </div>
      </Reveal>

      <div className="project__body">
        <Reveal className="project__info">
          <p>{p.summary}</p>
          <dl className="meta">
            {p.meta.map((m) => (
              <div key={m.label}><dt>{m.label}</dt><dd>{m.value}</dd></div>
            ))}
          </dl>
          <h4 className="mini-title">Technologies used</h4>
          <ul className="tags tags--wrap">
            {p.tech.map((t) => <li key={t}>{t}</li>)}
          </ul>
          {!hasRepo && <p className="note">Source code / live demo links are not published for this project.</p>}
        </Reveal>

        <Reveal className="project__features" delay={100}>
          <h4 className="mini-title">Main features</h4>
          <ul className="checks checks--2">
            {p.features.map((f) => <li key={f}>{f}</li>)}
          </ul>
        </Reveal>
      </div>

      <div className="project__gallery">
        <div className="gallery-head">
          <h4 className="mini-title">Original screenshots</h4>
          {p.modules.length > 1 && (
            <div className="tabs" role="tablist" aria-label={`${p.title} modules`}>
              {p.modules.map((m) => (
                <button
                  key={m.id}
                  role="tab"
                  aria-selected={tab === m.id}
                  className={tab === m.id ? 'is-active' : ''}
                  onClick={() => setTab(m.id)}
                >
                  {m.label} <span>{m.shots.length}</span>
                </button>
              ))}
            </div>
          )}
        </div>
        <p className="gallery-blurb">{mod.blurb}</p>
        <Gallery key={`${p.id}-${tab}`} shots={mod.shots} layout={p.layout} alt={`${p.title} ${mod.label}`} />
        {repo && (
          <div className="repo">
            <a
              className="repo__link"
              href={repo.url}
              target="_blank"
              rel="noopener noreferrer"
              aria-label={`${repo.label} on GitHub (opens in a new tab)`}
              title={`${repo.label} on GitHub`}
            >
              <Icon name="github" size={20} />
              <span>{repo.label}</span>
            </a>
          </div>
        )}
      </div>

      {p.bill && <BillViewer bill={p.bill} />}
    </article>
  )
}

export default function Projects() {
  return (
    <section id="projects" className="section section--alt">
      <div className="container">
        <SectionHeading
          eyebrow="Things I've built"
          title="My projects"
          text="Three complete projects – two Android applications and one web system. Every screenshot below comes from my original project documentation."
        />
        <div className="project-nav">
          {projects.map((p) => (
            <a key={p.id} href={`#${p.id}`} className="project-nav__item">
              <span>{p.index}</span>
              <strong>{p.title}</strong>
              <em>{p.type}</em>
            </a>
          ))}
        </div>
        {projects.map((p) => <Project key={p.id} p={p} />)}
      </div>
    </section>
  )
}
